"""Build a local web page with one-click copy buttons for application forms.

The page is generated by plain code from the extracted CV data, not by Claude.
Every value is HTML-escaped, so text from the CV (or a model) can never
inject markup or scripts into the page.
"""

from datetime import datetime
from html import escape
from pathlib import Path

from job_analyzer import paths
from job_analyzer.models import Certification, CVDetails, Education, WorkExperience


def _dates(start: str | None, end: str | None) -> str:
    return " – ".join(d for d in (start, end) if d)


def experience_text(e: WorkExperience) -> str:
    head = f"{e.job_title} — {e.company}" + (f" ({e.location})" if e.location else "")
    return "\n".join(x for x in (head, _dates(e.start_date, e.end_date), e.description) if x)


def education_text(e: Education) -> str:
    degree = ", ".join(x for x in (e.degree, e.field_of_study) if x)
    head = f"{degree} — {e.institution}" if degree else e.institution
    if e.location:
        head += f" ({e.location})"
    return "\n".join(x for x in (head, _dates(e.start_date, e.end_date), e.details) if x)


def certification_text(c: Certification) -> str:
    parts = [c.name + (f" — {c.issuer}" if c.issuer else "")]
    if c.issue_date or c.expiry_date:
        parts.append(f"Issued {c.issue_date or '?'}" + (f", expires {c.expiry_date}" if c.expiry_date else ""))
    if c.credential_id:
        parts.append(f"Credential ID: {c.credential_id}")
    if c.url:
        parts.append(c.url)
    if c.details:
        parts.append(c.details)
    return "\n".join(parts)


def _button(text: str, label: str = "Copy") -> str:
    return f'<button class="copy" data-copy="{escape(text, quote=True)}">{escape(label)}</button>'


def _field(label: str, value: str | None) -> str:
    if not value:
        return ""
    return (
        f'<div class="field"><span class="label">{escape(label)}</span>'
        f'<span class="value">{escape(value)}</span>{_button(value)}</div>'
    )


def _card(title: str, all_text: str, fields: list[tuple[str, str | None]]) -> str:
    rows = "".join(_field(label, value) for label, value in fields)
    return (
        f'<article class="card"><header><h3>{escape(title)}</h3>'
        f'{_button(all_text, "Copy all")}</header>{rows}</article>'
    )


def _section(title: str, cards: list[str], all_texts: list[str]) -> str:
    if not cards:
        return f'<section><h2>{escape(title)}</h2><p class="empty">None found in your CV.</p></section>'
    whole = "\n\n".join(all_texts)
    return (
        f'<section><div class="section-head"><h2>{escape(title)}</h2>'
        f'{_button(whole, "Copy whole section")}</div>{"".join(cards)}</section>'
    )


def build_html(d: CVDetails, cv_name: str) -> str:
    exp_texts = [experience_text(e) for e in d.experience]
    exp_cards = [
        _card(f"{e.job_title} · {e.company}", t, [
            ("Job title", e.job_title), ("Company", e.company), ("Location", e.location),
            ("Start date", e.start_date), ("End date", e.end_date), ("Description", e.description),
        ])
        for e, t in zip(d.experience, exp_texts)
    ]
    edu_texts = [education_text(e) for e in d.education]
    edu_cards = [
        _card(e.degree or e.institution, t, [
            ("Institution", e.institution), ("Degree", e.degree), ("Field of study", e.field_of_study),
            ("Location", e.location), ("Start date", e.start_date), ("End date", e.end_date),
            ("Details", e.details),
        ])
        for e, t in zip(d.education, edu_texts)
    ]
    cert_texts = [certification_text(c) for c in d.certifications]
    cert_cards = [
        _card(c.name, t, [
            ("Name", c.name), ("Issuer", c.issuer), ("Issue date", c.issue_date),
            ("Expiry date", c.expiry_date), ("Credential ID", c.credential_id), ("URL", c.url),
            ("Details", c.details),
        ])
        for c, t in zip(d.certifications, cert_texts)
    ]
    generated = datetime.now().strftime("%d %b %Y, %H:%M")
    body = (
        _section("Work experience", exp_cards, exp_texts)
        + _section("Education", edu_cards, edu_texts)
        + _section("Certifications", cert_cards, cert_texts)
    )
    return PAGE.format(cv_name=escape(cv_name), generated=generated, body=body)


def write_copy_kit(d: CVDetails, cv_name: str, path: Path | None = None) -> Path:
    path = path or paths.copy_kit_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_html(d, cv_name), encoding="utf-8")
    return path


